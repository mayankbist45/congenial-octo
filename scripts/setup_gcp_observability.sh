#!/bin/bash
# Provision logs-based metrics and alert policies for the VM deployment.
#
# Requires:
#   gcloud auth application-default login   (or an already-authenticated shell)
#   GCP project owner/editor or equivalent Monitoring + Logging permissions
#
# Optional env:
#   GCP_PROJECT=congenial-octo
#   ALERT_EMAILS=mayankbist45@gmail.com,calanpereira98@gmail.com

set -euo pipefail

PROJECT="${GCP_PROJECT:-$(gcloud config get-value project 2>/dev/null)}"
ALERT_EMAILS="${ALERT_EMAILS:-mayankbist45@gmail.com,calanpereira98@gmail.com}"
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

if [ -z "$PROJECT" ]; then
    echo "error: set GCP_PROJECT or configure gcloud default project" >&2
    exit 1
fi

METRIC_PREFIX="mfm"

access_token() {
    gcloud auth print-access-token
}

monitoring_api() {
    local method="$1"
    local url="$2"
    local body="${3:-}"
    if [ -n "$body" ]; then
        curl -fsSL -X "$method" \
            -H "Authorization: Bearer $(access_token)" \
            -H "Content-Type: application/json" \
            "$url" \
            -d "$body"
    else
        curl -fsSL -X "$method" \
            -H "Authorization: Bearer $(access_token)" \
            "$url"
    fi
}

upsert_metric() {
    local name="$1"
    local description="$2"
    local filter="$3"
    if gcloud logging metrics describe "$name" --project "$PROJECT" >/dev/null 2>&1; then
        gcloud logging metrics update "$name" \
            --project "$PROJECT" \
            --description "$description" \
            --log-filter "$filter" >/dev/null
        echo "updated metric: $name"
    else
        gcloud logging metrics create "$name" \
            --project "$PROJECT" \
            --description "$description" \
            --log-filter "$filter" >/dev/null
        echo "created metric: $name"
    fi
}

ensure_email_channel() {
    local email="$1"
    local response existing
    response="$(monitoring_api GET "https://monitoring.googleapis.com/v3/projects/${PROJECT}/notificationChannels")"
    existing="$(RESPONSE="$response" python3 - "$email" <<'PY'
import json, os, sys
email = sys.argv[1]
payload = json.loads(os.environ["RESPONSE"])
for item in payload.get("notificationChannels", []):
    labels = item.get("labels") or {}
    if item.get("type") == "email" and labels.get("email_address") == email:
        print(item["name"])
        raise SystemExit(0)
raise SystemExit(1)
PY
    )" || true
    if [ -n "$existing" ]; then
        echo "$existing"
        return 0
    fi
    monitoring_api POST \
        "https://monitoring.googleapis.com/v3/projects/${PROJECT}/notificationChannels" \
        "$(python3 - "$email" <<'PY'
import json, sys
email = sys.argv[1]
print(json.dumps({
    "type": "email",
    "displayName": f"Fund Ops {email}",
    "description": "Portfolio manager observability alerts",
    "labels": {"email_address": email},
}))
PY
)" | python3 -c 'import json,sys; print(json.load(sys.stdin)["name"])'
}

metric_filter() {
    local text="$1"
    printf 'resource.type="gce_instance" AND textPayload =~ "OPS_EVENT" AND %s' "$text"
}

create_policy_file() {
    local path="$1"
    local display_name="$2"
    local body="$3"
    cat >"$path" <<EOF
{
  "displayName": "$display_name",
  "enabled": true,
  "combiner": "OR",
  "documentation": {
    "content": "Generated by scripts/setup_gcp_observability.sh. Investigate the /operations page and Cloud Logging for OPS_EVENT entries.",
    "mimeType": "text/markdown"
  },
  "conditions": [
$body
  ]
}
EOF
}

create_threshold_condition() {
    local display_name="$1"
    local metric_type="$2"
    local duration="$3"
    local threshold="$4"
    cat <<EOF
    {
      "displayName": "$display_name",
      "conditionThreshold": {
        "filter": "metric.type=\\"logging.googleapis.com/user/$metric_type\\"",
        "comparison": "COMPARISON_GT",
        "thresholdValue": $threshold,
        "duration": "$duration",
        "aggregations": [
          {
            "alignmentPeriod": "300s",
            "perSeriesAligner": "ALIGN_SUM"
          }
        ],
        "trigger": {
          "count": 1
        }
      }
    }
EOF
}

create_absence_condition() {
    local display_name="$1"
    local metric_type="$2"
    local duration="$3"
    cat <<EOF
    {
      "displayName": "$display_name",
      "conditionAbsent": {
        "filter": "metric.type=\\"logging.googleapis.com/user/$metric_type\\"",
        "duration": "$duration",
        "aggregations": [
          {
            "alignmentPeriod": "300s",
            "perSeriesAligner": "ALIGN_SUM"
          }
        ],
        "trigger": {
          "count": 1
        }
      }
    }
EOF
}

daily_success_metric="${METRIC_PREFIX}_long_cycle_success_count"
daily_failure_metric="${METRIC_PREFIX}_long_cycle_failure_count"
close_success_metric="${METRIC_PREFIX}_close_success_count"
close_failure_metric="${METRIC_PREFIX}_close_failure_count"
backup_success_metric="${METRIC_PREFIX}_backup_success_count"
backup_failure_metric="${METRIC_PREFIX}_backup_failure_count"
india_heartbeat_metric="${METRIC_PREFIX}_intraday_heartbeat_india_count"
us_heartbeat_metric="${METRIC_PREFIX}_intraday_heartbeat_us_count"
india_launcher_failure_metric="${METRIC_PREFIX}_intraday_launcher_failure_india_count"
us_launcher_failure_metric="${METRIC_PREFIX}_intraday_launcher_failure_us_count"
dashboard_restart_metric="${METRIC_PREFIX}_dashboard_restart_count"

upsert_metric "$daily_success_metric" "Long cycle success events" "$(metric_filter 'textPayload =~ "\\\"event\\\": \\\"scheduled_run\\\"" AND textPayload =~ "\\\"job\\\": \\\"long_cycle\\\"" AND textPayload =~ "\\\"status\\\": \\\"success\\\""')"
upsert_metric "$daily_failure_metric" "Long cycle failure events" "$(metric_filter 'textPayload =~ "\\\"event\\\": \\\"scheduled_run\\\"" AND textPayload =~ "\\\"job\\\": \\\"long_cycle\\\"" AND textPayload =~ "\\\"status\\\": \\\"failure\\\""')"
upsert_metric "$close_success_metric" "Close run success events" "$(metric_filter 'textPayload =~ "\\\"event\\\": \\\"scheduled_run\\\"" AND textPayload =~ "\\\"job\\\": \\\"close\\\"" AND textPayload =~ "\\\"status\\\": \\\"success\\\""')"
upsert_metric "$close_failure_metric" "Close run failure events" "$(metric_filter 'textPayload =~ "\\\"event\\\": \\\"scheduled_run\\\"" AND textPayload =~ "\\\"job\\\": \\\"close\\\"" AND textPayload =~ "\\\"status\\\": \\\"failure\\\""')"
upsert_metric "$backup_success_metric" "Backup upload success events" "$(metric_filter 'textPayload =~ "\\\"event\\\": \\\"backup_upload\\\"" AND textPayload =~ "\\\"status\\\": \\\"success\\\""')"
upsert_metric "$backup_failure_metric" "Backup failures and upload failures" "$(metric_filter '((textPayload =~ "\\\"event\\\": \\\"backup_run\\\"" OR textPayload =~ "\\\"event\\\": \\\"backup_upload\\\"") AND textPayload =~ "\\\"status\\\": \\\"failure\\\"")')"
upsert_metric "$india_heartbeat_metric" "India intraday heartbeats" "$(metric_filter 'textPayload =~ "\\\"event\\\": \\\"intraday_heartbeat\\\"" AND textPayload =~ "\\\"market_id\\\": \\\"india_equity\\\""')"
upsert_metric "$us_heartbeat_metric" "US intraday heartbeats" "$(metric_filter 'textPayload =~ "\\\"event\\\": \\\"intraday_heartbeat\\\"" AND textPayload =~ "\\\"market_id\\\": \\\"us_equity\\\""')"
upsert_metric "$india_launcher_failure_metric" "India launcher failures" "$(metric_filter 'textPayload =~ "\\\"event\\\": \\\"intraday_launcher\\\"" AND textPayload =~ "\\\"market_id\\\": \\\"india_equity\\\"" AND textPayload =~ "\\\"status\\\": \\\"failure\\\""')"
upsert_metric "$us_launcher_failure_metric" "US launcher failures" "$(metric_filter 'textPayload =~ "\\\"event\\\": \\\"intraday_launcher\\\"" AND textPayload =~ "\\\"market_id\\\": \\\"us_equity\\\"" AND textPayload =~ "\\\"status\\\": \\\"failure\\\""')"
upsert_metric "$dashboard_restart_metric" "Dashboard startup events" "$(metric_filter 'textPayload =~ "\\\"event\\\": \\\"dashboard_service\\\"" AND textPayload =~ "\\\"status\\\": \\\"start\\\""')"

IFS=',' read -r -a email_array <<<"$ALERT_EMAILS"
CHANNELS=()
for email in "${email_array[@]}"; do
    trimmed="$(echo "$email" | xargs)"
    [ -n "$trimmed" ] || continue
    CHANNELS+=("$(ensure_email_channel "$trimmed")")
done
CHANNEL_ARG="$(IFS=,; echo "${CHANNELS[*]}")"

create_policy_file \
    "$TMP_DIR/daily-failure.json" \
    "MFM Morning Run Failure" \
    "$(create_threshold_condition "long_cycle failures > 0" "$daily_failure_metric" "0s" 0)"

create_policy_file \
    "$TMP_DIR/close-failure.json" \
    "MFM Close Run Failure" \
    "$(create_threshold_condition "close failures > 0" "$close_failure_metric" "0s" 0)"

create_policy_file \
    "$TMP_DIR/backup-failure.json" \
    "MFM Backup Failure" \
    "$(create_threshold_condition "backup failures > 0" "$backup_failure_metric" "0s" 0)"

create_policy_file \
    "$TMP_DIR/india-launcher-failure.json" \
    "MFM India Intraday Launcher Failure" \
    "$(create_threshold_condition "india launcher failures > 0" "$india_launcher_failure_metric" "0s" 0)"

create_policy_file \
    "$TMP_DIR/us-launcher-failure.json" \
    "MFM US Intraday Launcher Failure" \
    "$(create_threshold_condition "us launcher failures > 0" "$us_launcher_failure_metric" "0s" 0)"

create_policy_file \
    "$TMP_DIR/dashboard-restarts.json" \
    "MFM Dashboard Repeated Restarts" \
    "$(create_threshold_condition "dashboard starts > 3 in 1h" "$dashboard_restart_metric" "3600s" 3)"

create_policy_file \
    "$TMP_DIR/daily-missed.json" \
    "MFM Morning Run Missing" \
    "$(create_absence_condition "no morning success signal" "$daily_success_metric" "14400s")"

create_policy_file \
    "$TMP_DIR/close-missed.json" \
    "MFM Close Run Missing" \
    "$(create_absence_condition "no close success signal" "$close_success_metric" "21600s")"

create_policy_file \
    "$TMP_DIR/backup-missed.json" \
    "MFM Backup Missing" \
    "$(create_absence_condition "no backup success signal" "$backup_success_metric" "21600s")"

create_policy_file \
    "$TMP_DIR/india-heartbeat-missed.json" \
    "MFM India Intraday Heartbeat Missing" \
    "$(create_absence_condition "no india intraday heartbeat" "$india_heartbeat_metric" "900s")"

create_policy_file \
    "$TMP_DIR/us-heartbeat-missed.json" \
    "MFM US Intraday Heartbeat Missing" \
    "$(create_absence_condition "no us intraday heartbeat" "$us_heartbeat_metric" "900s")"

for policy in "$TMP_DIR"/*.json; do
    gcloud monitoring policies create \
        --project "$PROJECT" \
        --notification-channels="$CHANNEL_ARG" \
        --policy-from-file="$policy" >/dev/null || true
    echo "applied policy template: $(basename "$policy")"
done

echo
echo "Observability provisioning complete for project: $PROJECT"
echo "Notification channels:"
printf '  %s\n' "${CHANNELS[@]}"
echo
echo "Note: email channels may require verification before alerts deliver."
echo "Tune absence durations after observing one full trading week."
