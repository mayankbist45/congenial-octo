#!/bin/bash
# Install (or remove) the launchd jobs that run the fund unattended.
#
# Two jobs, both weekdays only:
#   08:15 IST  cycle  - research, self-approve, place simulated orders
#   18:00 IST  close  - mark the book at closing prices and record NAV
#
# The close runs well after the 15:30 bell because the free price feed publishes
# the official close with a lag; marking at 16:00 would often re-use yesterday's.
#
# The executable launchd calls lives under ~/Library/Application Support, not
# under Documents. macOS TCC blocks background agents from running scripts
# inside Documents ("Operation not permitted"), which is what killed the first
# 08:15 attempt.
#
#   ./scripts/install_schedule.sh            install and start
#   ./scripts/install_schedule.sh --status   show whether they are loaded
#   ./scripts/install_schedule.sh --remove   uninstall
#   ./scripts/install_schedule.sh --test     fire a one-shot status via launchd
#
# The laptop must be awake at those times. To have macOS wake itself:
#   sudo pmset repeat wakeorpoweron MTWRF 08:10:00

set -uo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
AGENTS_DIR="$HOME/Library/LaunchAgents"
SUPPORT_DIR="$HOME/Library/Application Support/MutualFundManager"
LAUNCHER="$SUPPORT_DIR/run_scheduled.sh"
DOMAIN="gui/$(id -u)"

PREMARKET_LABEL="com.mutualfund.premarket"
CLOSE_LABEL="com.mutualfund.close"

install_launcher() {
    mkdir -p "$SUPPORT_DIR" "$PROJECT_DIR/data"
    # Bake the project path in: launchd's working directory is unreliable under TCC.
    cat >"$LAUNCHER" <<EOF
#!/bin/bash
# Auto-generated by scripts/install_schedule.sh — do not edit by hand.
set -uo pipefail
PROJECT_DIR="$PROJECT_DIR"
cd "\$PROJECT_DIR" || exit 1
COMMAND="\${1:-cycle}"
shift || true
PYTHON="\$PROJECT_DIR/.venv/bin/python"
LOG="\$PROJECT_DIR/data/scheduled.log"
mkdir -p "\$PROJECT_DIR/data"
export PATH="/opt/homebrew/bin:/opt/homebrew/opt/postgresql@17/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
{
    echo ""
    echo "=================================================================="
    echo "\$(date '+%Y-%m-%d %H:%M:%S %Z')  run_daily.py \$COMMAND \$*"
    echo "=================================================================="
} >>"\$LOG"
if [ ! -x "\$PYTHON" ]; then
    echo "FATAL: no virtualenv at \$PYTHON" >>"\$LOG"
    exit 1
fi
"\$PYTHON" run_daily.py "\$COMMAND" "\$@" >>"\$LOG" 2>&1
STATUS=\$?
if [ \$STATUS -eq 0 ]; then
    echo "--- finished cleanly at \$(date '+%H:%M:%S') ---" >>"\$LOG"
else
    echo "--- FAILED with exit \$STATUS at \$(date '+%H:%M:%S') ---" >>"\$LOG"
fi
exit \$STATUS
EOF
    chmod +x "$LAUNCHER"
    echo "  launcher -> $LAUNCHER"
}

write_plist() {
    local label="$1" command="$2" hour="$3" minute="$4"
    local path="$AGENTS_DIR/$label.plist"

    {
        cat <<XML
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>$label</string>
    <key>ProgramArguments</key>
    <array>
        <string>$LAUNCHER</string>
        <string>$command</string>
    </array>
    <key>WorkingDirectory</key>
    <string>$PROJECT_DIR</string>
    <key>StartCalendarInterval</key>
    <array>
XML
        for weekday in 1 2 3 4 5; do
            cat <<XML
        <dict>
            <key>Weekday</key><integer>$weekday</integer>
            <key>Hour</key><integer>$hour</integer>
            <key>Minute</key><integer>$minute</integer>
        </dict>
XML
        done
        cat <<XML
    </array>
    <key>StandardOutPath</key>
    <string>$SUPPORT_DIR/launchd.log</string>
    <key>StandardErrorPath</key>
    <string>$SUPPORT_DIR/launchd.log</string>
    <key>RunAtLoad</key>
    <false/>
    <key>ProcessType</key>
    <string>Background</string>
</dict>
</plist>
XML
    } >"$path"

    echo "  wrote $path"
}

load_job() {
    local label="$1"
    launchctl bootout "$DOMAIN/$label" 2>/dev/null
    if launchctl bootstrap "$DOMAIN" "$AGENTS_DIR/$label.plist" 2>/dev/null; then
        echo "  loaded $label"
    else
        echo "  FAILED to load $label" >&2
        return 1
    fi
}

case "${1:-install}" in
--remove)
    for label in "$PREMARKET_LABEL" "$CLOSE_LABEL"; do
        launchctl bootout "$DOMAIN/$label" 2>/dev/null && echo "  unloaded $label"
        rm -f "$AGENTS_DIR/$label.plist" && echo "  removed $label.plist"
    done
    rm -f "$LAUNCHER"
    echo "Schedule removed. The fund will no longer run on its own."
    ;;

--status)
    for label in "$PREMARKET_LABEL" "$CLOSE_LABEL"; do
        if launchctl print "$DOMAIN/$label" >/dev/null 2>&1; then
            detail=$(launchctl print "$DOMAIN/$label" 2>/dev/null |
                grep -E "runs =|last exit code" | tr '\n' ' ' | sed 's/  */ /g')
            echo "  $label: loaded ($detail)"
        else
            echo "  $label: not loaded"
        fi
    done
    echo "  launcher: $LAUNCHER"
    echo "  app log:  $PROJECT_DIR/data/scheduled.log"
    echo "  agent log:$SUPPORT_DIR/launchd.log"
    ;;

--test)
    install_launcher
    # One-shot agent that only runs status, to prove TCC will allow it.
    local_label="com.mutualfund.permissiontest"
    cat >"$AGENTS_DIR/$local_label.plist" <<XML
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key><string>$local_label</string>
    <key>ProgramArguments</key>
    <array>
        <string>$LAUNCHER</string>
        <string>status</string>
    </array>
    <key>WorkingDirectory</key><string>$PROJECT_DIR</string>
    <key>StandardOutPath</key><string>$SUPPORT_DIR/launchd.log</string>
    <key>StandardErrorPath</key><string>$SUPPORT_DIR/launchd.log</string>
    <key>RunAtLoad</key><true/>
</dict>
</plist>
XML
    launchctl bootout "$DOMAIN/$local_label" 2>/dev/null
    launchctl bootstrap "$DOMAIN" "$AGENTS_DIR/$local_label.plist"
    sleep 3
    echo "--- launchd.log ---"
    tail -20 "$SUPPORT_DIR/launchd.log" 2>/dev/null || true
    echo "--- scheduled.log (tail) ---"
    tail -25 "$PROJECT_DIR/data/scheduled.log" 2>/dev/null || true
    launchctl bootout "$DOMAIN/$local_label" 2>/dev/null
    rm -f "$AGENTS_DIR/$local_label.plist"
    ;;

install)
    mkdir -p "$AGENTS_DIR" "$PROJECT_DIR/data"
    chmod +x "$PROJECT_DIR/scripts/run_scheduled.sh"

    echo "Installing schedule for $PROJECT_DIR"
    install_launcher
    write_plist "$PREMARKET_LABEL" cycle 8 15
    write_plist "$CLOSE_LABEL" close 18 0
    load_job "$PREMARKET_LABEL" || exit 1
    load_job "$CLOSE_LABEL" || exit 1

    echo
    echo "Scheduled, weekdays only:"
    echo "  08:15  full cycle (research, self-approve, simulated orders)"
    echo "  18:00  close of day (mark to closing prices, record NAV)"
    echo
    echo "Watch progress:  tail -f data/scheduled.log"
    echo "Permission test: ./scripts/install_schedule.sh --test"
    echo
    echo "If jobs still exit 126, grant Full Disk Access to /bin/bash:"
    echo "  System Settings → Privacy & Security → Full Disk Access"
    ;;

*)
    echo "Usage: $0 [install|--status|--remove|--test]" >&2
    exit 2
    ;;
esac
