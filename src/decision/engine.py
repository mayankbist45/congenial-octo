"""Decision layer.

Turns the daily briefing into a set of trade proposals. The layering matters:

- Mandatory risk trades are generated by the risk engine and never touch the LLM.
  A stop-loss is not a matter of opinion.
- Discretionary trades come from the LLM, which reads the briefing and returns
  structured JSON. Its output is parsed defensively, sized by the fund's own
  rules, and then re-validated by the risk engine.
- If the LLM is unavailable or its response is unusable, the run continues on the
  rules-only path. The fund must still function without it.

The decision layer has no authority of its own: everything it produces is a
*proposal*, and nothing is placed without human approval.
"""

from __future__ import annotations

from datetime import date
from typing import Any, Dict, List, Optional, Tuple

from src.config import Config, get_config
from src.decision.briefing import BriefingBuilder
from src.decision.prompts import (
    CLOSING_DEEP_REVIEW,
    CLOSING_NORMAL,
    DEEP_REVIEW_ADDENDUM,
    SYSTEM_PROMPT,
    USER_TEMPLATE,
    persona_system_prompt,
)
from src.llm import LLMClient, LLMUnavailable
from src.logging_setup import get_logger
from src.models import (
    Action,
    DailyDecision,
    FactorScores,
    FundamentalSnapshot,
    NewsDigest,
    EarningsDigest,
    PortfolioRiskProfile,
    PortfolioState,
    Severity,
    TechnicalSnapshot,
    TradeProposal,
    Trigger,
    TriggerType,
)
from src.risk.engine import RiskEngine
from src.universe import Universe, load_universe

logger = get_logger(__name__)

MAX_PROPOSALS_PER_DAY = 5
MAX_PROPOSALS_DEEP_REVIEW = 10
# Buys per run on the rules-only path. Kept small so building a portfolio without
# a decision layer happens gradually and under repeated human review.
MAX_RULES_ONLY_BUYS = 3


def is_deep_review_day(config: Config, as_of: Optional[date] = None) -> bool:
    """True on the quarterly full-portfolio review date.

    Falls back to any day in the review month once the nominal day has passed, so
    a missed run (holiday, outage) does not skip a quarter entirely.
    """
    as_of = as_of or date.today()
    months = config.get("cadence.deep_review_months", []) or []
    day = int(config.get("cadence.deep_review_day", 1) or 1)
    return as_of.month in months and as_of.day == day


class DecisionEngine:
    """Produces the day's proposals and the memo explaining them."""

    def __init__(
        self,
        config: Optional[Config] = None,
        llm: Optional[LLMClient] = None,
        risk_engine: Optional[RiskEngine] = None,
        universe: Optional[Universe] = None,
    ):
        self._config = config or get_config()
        self._llm = llm or LLMClient(self._config)
        self._universe = universe or load_universe(self._config)
        self._risk = risk_engine or RiskEngine(self._config, self._universe)
        self._briefings = BriefingBuilder(self._config)

    # ------------------------------------------------------------------
    def decide(
        self,
        portfolio: PortfolioState,
        scores: Dict[str, FactorScores],
        fundamentals: Dict[str, FundamentalSnapshot],
        technicals: Dict[str, TechnicalSnapshot],
        triggers: List[Trigger],
        candidates: List[FactorScores],
        digest: Optional[NewsDigest] = None,
        earnings: Optional[EarningsDigest] = None,
        risk_profile: Optional[PortfolioRiskProfile] = None,
        as_of: Optional[date] = None,
    ) -> DailyDecision:
        """Run one full decision cycle."""
        as_of = as_of or portfolio.as_of
        deep_review = is_deep_review_day(self._config, as_of)
        turnover = self._risk.turnover_status(as_of)

        # 1. Rules first. These are already decided.
        mandatory = self._risk.mandatory_proposals(triggers, portfolio, technicals)

        # 2. The briefing the decision maker sees.
        briefing = self._briefings.build(
            portfolio=portfolio,
            scores=scores,
            fundamentals=fundamentals,
            technicals=technicals,
            triggers=triggers,
            candidates=candidates,
            digest=digest,
            earnings=earnings,
            risk_profile=risk_profile,
            turnover=turnover,
            is_deep_review=deep_review,
            as_of=as_of,
        )

        # 3. Discretionary proposals.
        discretionary, memo, llm_used = self._propose(
            briefing, portfolio, technicals, triggers, candidates, deep_review
        )

        # 4. Everything is re-validated together, so the batch as a whole
        #    respects the cash buffer and the caps.
        validation = self._risk.validate(
            mandatory + discretionary, portfolio, technicals, scores, turnover
        )

        if validation.rejected:
            memo = self._append_rejections(memo, validation.rejected)

        decision = DailyDecision(
            as_of=as_of,
            is_deep_review=deep_review,
            proposals=validation.approved,
            rejected=validation.rejected,
            memo=memo,
            triggers=triggers,
            turnover_used_pct=turnover.used_pct,
            turnover_budget_pct=turnover.budget_pct,
            risk_profile=risk_profile,
            digest=digest,
            llm_used=llm_used,
        )

        logger.info(
            "Decision for %s: %d proposal(s)%s",
            as_of.isoformat(),
            len(decision.proposals),
            " [deep review]" if deep_review else "",
        )
        return decision

    # ------------------------------------------------------------------
    def _propose(
        self,
        briefing: str,
        portfolio: PortfolioState,
        technicals: Dict[str, TechnicalSnapshot],
        triggers: List[Trigger],
        candidates: List[FactorScores],
        deep_review: bool,
    ) -> Tuple[List[TradeProposal], str, bool]:
        """Ask the LLM for proposals, falling back to rules-only."""

        def fall_back(reason: str) -> Tuple[List[TradeProposal], str, bool]:
            proposals = self._rules_only_proposals(
                portfolio, technicals, triggers, candidates
            )
            return proposals, self._rules_only_memo(triggers, reason, proposals), False

        if not self._llm.available:
            logger.info("No LLM configured; running rules-only")
            return fall_back("no LLM configured")

        base_prompt = persona_system_prompt(self._config)
        system = base_prompt + (DEEP_REVIEW_ADDENDUM if deep_review else "")
        closing = CLOSING_DEEP_REVIEW if deep_review else CLOSING_NORMAL
        user = USER_TEMPLATE.format(briefing=briefing, closing=closing)

        try:
            payload = self._llm.complete_json(system, user)
        except LLMUnavailable as exc:
            logger.error("Decision layer LLM call failed: %s", exc)
            return fall_back(str(exc))

        if not isinstance(payload, dict):
            logger.error("Decision response was not a JSON object")
            return fall_back("unusable LLM response")

        memo = self._memo_from(payload)
        proposals = self._parse_proposals(payload, portfolio, technicals, deep_review)
        return proposals, memo, True

    def _memo_from(self, payload: Dict[str, Any]) -> str:
        parts: List[str] = []
        for label, key in (
            ("Market view", "market_view"),
            ("Portfolio assessment", "portfolio_assessment"),
            ("Reasoning", "reasoning"),
        ):
            value = payload.get(key)
            if isinstance(value, str) and value.strip():
                parts.append(f"{label}: {value.strip()}")
        if not parts:
            return "The decision layer returned no commentary."
        return "\n\n".join(parts)

    def _rules_only_proposals(
        self,
        portfolio: PortfolioState,
        technicals: Dict[str, TechnicalSnapshot],
        triggers: List[Trigger],
        candidates: List[FactorScores],
    ) -> List[TradeProposal]:
        """Deploy idle cash mechanically when the decision layer is unavailable.

        Without this, a fund with no LLM configured would hold cash forever: the
        hard rules can sell but never buy, since choosing what to own is exactly
        the judgement the decision layer provides. The mechanical substitute is
        deliberately dull - buy the top of the quantitative screen, sized by the
        fund's own rules, a few names at a time - and it only runs when the fund
        is genuinely under-invested against its mandate. A human still approves
        every one of these.
        """
        deploying = any(
            t.trigger_type in (TriggerType.INITIAL_BUILD, TriggerType.UNDERWEIGHT_DEPLOY)
            for t in triggers
        )
        if not deploying or not candidates:
            return []

        proposals: List[TradeProposal] = []
        for score in candidates:
            if len(proposals) >= MAX_RULES_ONLY_BUYS:
                break
            symbol = score.symbol
            if portfolio.get(symbol) is not None:
                continue

            technical = technicals.get(symbol)
            price = technical.last_price if technical and technical.has_price else None
            if not price:
                continue

            sizing = self._risk.sizer.size_new_position(
                portfolio, symbol, price, technical
            )
            if not sizing.is_actionable:
                continue

            proposals.append(
                TradeProposal(
                    symbol=symbol,
                    action=Action.BUY,
                    quantity=sizing.quantity,
                    rationale=(
                        f"[quant_screen] Ranks {score.rank or '-'} in the screened "
                        f"universe on composite factor score {score.composite:+.2f} "
                        f"(quality {score.quality:+.2f}, value {score.value:+.2f}, "
                        f"growth {score.growth:+.2f}, momentum {score.momentum:+.2f}), "
                        f"and passes every fundamental gate. Proposed mechanically "
                        f"because the fund is holding {portfolio.cash_pct:.0f}% cash "
                        f"and the decision layer is unavailable to exercise judgement."
                    ),
                    trigger_types=[TriggerType.UNDERWEIGHT_DEPLOY.value],
                    confidence=None,
                    reference_price=price,
                    estimated_value=sizing.value,
                    company_name=self._universe.company_name_of(symbol),
                    sector=self._universe.sector_of(symbol),
                    source="quant_screen",
                    thesis=(
                        "Held on quantitative merit alone: no qualitative thesis was "
                        "written, because no decision layer was available to write one."
                    ),
                )
            )

        if proposals:
            logger.info(
                "Rules-only deployment: proposing %d buy(s) from the screen",
                len(proposals),
            )
        return proposals

    def _rules_only_memo(
        self,
        triggers: List[Trigger],
        reason: str,
        proposals: Optional[List[TradeProposal]] = None,
    ) -> str:
        """Memo for the path where no discretionary judgement was applied."""
        mandatory = [t for t in triggers if t.severity == Severity.MANDATORY]
        lines = [
            f"Running on rules only ({reason}). No qualitative judgement was "
            f"applied to today's news or to the investment case for any holding."
        ]

        if proposals:
            lines.append("")
            lines.append(
                f"The fund is under-invested against its mandate, so {len(proposals)} "
                f"purchase(s) were proposed straight from the top of the quantitative "
                f"screen, sized by the fund's own rules: "
                + ", ".join(f"{p.symbol} ({p.quantity} shares)" for p in proposals)
                + ". These carry no written investment thesis and deserve more "
                "scrutiny than usual before approval."
            )

        if mandatory:
            lines.append("")
            lines.append(
                "Mandatory risk trades were still enforced: "
                + "; ".join(f"{t.symbol} ({t.trigger_type.value})" for t in mandatory)
            )
        else:
            lines.append("")
            lines.append("No mandatory risk rule fired, so the portfolio is unchanged.")

        discretionary = [t for t in triggers if t.severity != Severity.MANDATORY]
        if discretionary:
            lines.append("")
            lines.append(
                f"{len(discretionary)} trigger(s) needing judgement were left "
                f"unactioned and will be re-evaluated on the next run: "
                + "; ".join(
                    f"{t.symbol} ({t.trigger_type.value})" for t in discretionary[:10]
                )
            )
        return "\n".join(lines)

    # ------------------------------------------------------------------
    def _parse_proposals(
        self,
        payload: Dict[str, Any],
        portfolio: PortfolioState,
        technicals: Dict[str, TechnicalSnapshot],
        deep_review: bool,
    ) -> List[TradeProposal]:
        raw = payload.get("proposals")
        if not isinstance(raw, list) or not raw:
            return []

        limit = MAX_PROPOSALS_DEEP_REVIEW if deep_review else MAX_PROPOSALS_PER_DAY
        if len(raw) > limit:
            logger.warning(
                "Decision layer returned %d proposals; keeping the first %d",
                len(raw),
                limit,
            )
            raw = raw[:limit]

        proposals: List[TradeProposal] = []
        seen: set = set()

        for item in raw:
            proposal = self._parse_one(item, portfolio, technicals)
            if proposal is None:
                continue
            if proposal.symbol in seen:
                logger.warning("Duplicate proposal for %s discarded", proposal.symbol)
                continue
            seen.add(proposal.symbol)
            proposals.append(proposal)

        return proposals

    def _parse_one(
        self,
        item: Any,
        portfolio: PortfolioState,
        technicals: Dict[str, TechnicalSnapshot],
    ) -> Optional[TradeProposal]:
        """Build a proposal from one LLM item, or None if it is unusable."""
        if not isinstance(item, dict):
            return None

        symbol = str(item.get("symbol") or "").strip().upper()
        if not symbol:
            logger.warning("Proposal without a symbol discarded")
            return None

        action = self._parse_action(item.get("action"))
        if action is None or action == Action.HOLD:
            return None

        price = self._price_for(symbol, portfolio, technicals)
        if price is None:
            logger.warning("No price available for proposed %s; discarded", symbol)
            return None

        quantity = self._resolve_quantity(
            item.get("quantity"), symbol, action, price, portfolio, technicals
        )
        if quantity <= 0:
            logger.info(
                "Proposal for %s %s resolved to zero shares; discarded",
                action.value,
                symbol,
            )
            return None

        rationale = str(item.get("rationale") or "").strip()
        trigger = str(item.get("trigger") or "").strip()
        if not rationale:
            logger.warning("Proposal for %s has no rationale; discarded", symbol)
            return None
        if trigger:
            rationale = f"[{trigger}] {rationale}"

        return TradeProposal(
            symbol=symbol,
            action=action,
            quantity=quantity,
            rationale=rationale,
            trigger_types=[trigger] if trigger else [],
            confidence=self._parse_confidence(item.get("confidence")),
            reference_price=price,
            estimated_value=quantity * price,
            company_name=self._universe.company_name_of(symbol),
            sector=self._universe.sector_of(symbol),
            source="llm",
            thesis=str(item.get("thesis") or "").strip(),
            target_price=self._parse_float(item.get("target_price")),
        )

    @staticmethod
    def _parse_action(value: Any) -> Optional[Action]:
        if not value:
            return None
        try:
            return Action(str(value).strip().upper())
        except ValueError:
            logger.warning("Unrecognised action %r discarded", value)
            return None

    @staticmethod
    def _parse_float(value: Any) -> Optional[float]:
        if value is None:
            return None
        try:
            number = float(value)
        except (TypeError, ValueError):
            return None
        return number if number > 0 else None

    @staticmethod
    def _parse_confidence(value: Any) -> Optional[float]:
        if value is None:
            return None
        try:
            number = float(value)
        except (TypeError, ValueError):
            return None
        return min(max(number, 0.0), 1.0)

    def _price_for(
        self,
        symbol: str,
        portfolio: PortfolioState,
        technicals: Dict[str, TechnicalSnapshot],
    ) -> Optional[float]:
        technical = technicals.get(symbol)
        if technical and technical.has_price:
            return technical.last_price
        position = portfolio.get(symbol)
        if position and position.last_price > 0:
            return position.last_price
        return None

    def _resolve_quantity(
        self,
        requested: Any,
        symbol: str,
        action: Action,
        price: float,
        portfolio: PortfolioState,
        technicals: Dict[str, TechnicalSnapshot],
    ) -> int:
        """Decide the share count, sizing it ourselves when not given.

        A requested quantity is honoured but clipped: on the sell side to what is
        actually held, and on the buy side to what the fund's own sizing rules
        would allow. The model may express conviction through direction, not
        through position size.
        """
        position = portfolio.get(symbol)
        technical = technicals.get(symbol)

        if action in (Action.SELL, Action.TRIM):
            if position is None:
                return 0
            if action == Action.SELL and requested is None:
                return position.quantity
            quantity = self._as_int(requested)
            if quantity <= 0:
                # A trim with no size given halves the position, which is the
                # conventional partial exit.
                return max(position.quantity // 2, 1) if action == Action.TRIM else position.quantity
            return min(quantity, position.quantity)

        sizer = self._risk.sizer
        sizing = (
            sizer.size_add_to_position(portfolio, symbol, price, technical)
            if action == Action.ADD
            else sizer.size_new_position(portfolio, symbol, price, technical)
        )
        allowed = sizing.quantity

        requested_qty = self._as_int(requested)
        if requested_qty <= 0:
            if allowed > 0:
                logger.info(
                    "Sized %s at %d shares: %s",
                    symbol,
                    allowed,
                    "; ".join(sizing.reasons),
                )
            else:
                logger.info(
                    "Cannot size %s: %s", symbol, "; ".join(sizing.reasons)
                )
            return allowed

        if requested_qty > allowed:
            logger.info(
                "Requested %d shares of %s trimmed to %d by sizing rules (%s)",
                requested_qty,
                symbol,
                allowed,
                "; ".join(sizing.reasons),
            )
            return allowed
        return requested_qty

    @staticmethod
    def _as_int(value: Any) -> int:
        if value is None:
            return 0
        try:
            return int(float(value))
        except (TypeError, ValueError):
            return 0

    # ------------------------------------------------------------------
    @staticmethod
    def _append_rejections(
        memo: str, rejected: List[Tuple[TradeProposal, str]]
    ) -> str:
        """Record what the risk engine refused, so the record is complete."""
        lines = [memo, "", "--- REJECTED BY THE RISK ENGINE ---"]
        for proposal, reason in rejected:
            lines.append(
                f"{proposal.action.value} {proposal.quantity} x {proposal.symbol}: "
                f"{reason}"
            )
        return "\n".join(lines)
