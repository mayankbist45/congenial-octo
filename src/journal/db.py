"""Journal schema and connection handling.

The database is the fund's institutional memory: every decision (taken or
rejected) with its rationale, every fill, and the daily NAV series.

Two backends are supported from a single schema definition. PostgreSQL is the
one to run the fund on, because the journal is the durable record and a real
server gives concurrent access, proper backups and no risk of a half-written
file. SQLite is kept because it needs no server at all, which keeps the test
suite fast and lets someone try the fund out before installing anything.

Queries live in ``repository.py`` and are written once in a neutral dialect:
``?`` placeholders and ``GREATEST(a, b)`` for a scalar maximum. This module
translates both to whatever the active backend wants, so there is exactly one
place where the dialects differ.
"""

from __future__ import annotations

