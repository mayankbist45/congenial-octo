# Tables in dependency order, which the migration and test teardown both need.
TABLES = (
    "runs",
    "proposals",
    "trades",
    "position_meta",
    "position_snapshots",
    "nav_history",
    "risk_history",
    "news_digests",
    "liquid_positions",
    "decision_reviews",
    "learning_lessons",
)

# Tables whose primary key is a generated integer, so a migration that carries
# ids across has to move the sequence past them.
SEQUENCE_TABLES = ("runs", "proposals", "trades", "decision_reviews", "learning_lessons")

DbTarget = Union[None, str, Path, Config]


def resolve_url(target: DbTarget = None) -> str:
    """Work out which database to talk to.

    Accepts a DSN, a filesystem path (treated as SQLite), a Config, or nothing
    at all, in which case the active configuration decides.
    """
    if isinstance(target, str):
        return target
    if isinstance(target, Path):
        return f"{SQLITE_SCHEME}{target}"
    config = target if isinstance(target, Config) else get_config()
    return config.db_url


def is_postgres(url: str) -> bool:
    return url.startswith(POSTGRES_SCHEMES)


def dialect_of(url: str) -> str:
    return "postgres" if is_postgres(url) else "sqlite"


def sqlite_path(url: str) -> Path:
    """The file a SQLite DSN points at."""
    if url.startswith(SQLITE_SCHEME):
        return Path(url[len(SQLITE_SCHEME) :] or ":memory:")
    return Path(url)


def describe(url: str) -> str:
    """A log-safe description: never echoes a password."""
    if not is_postgres(url):
        return f"SQLite at {sqlite_path(url)}"
    return f"PostgreSQL at {re.sub(r'//[^@/]+@', '//', url)}"


def schema_for(dialect: str) -> str:
    tokens = _SCHEMA_TOKENS[dialect]
    return SCHEMA.format(**tokens)


def _translate(sql: str, dialect: str, has_params: bool) -> str:
    """Rewrite neutral SQL for the active backend.

    Queries use ``?`` placeholders and ``GREATEST`` throughout. No query in this
    project contains a ``?`` or ``%`` inside a string literal, which is what
    makes the substitution safe to do textually.
    """
    if dialect == "sqlite":
        # SQLite spells the scalar maximum as a two-argument max().
        return sql.replace("GREATEST(", "max(")
    if has_params:
        # psycopg treats % as the start of a placeholder once params are bound.
        sql = sql.replace("%", "%%")
    return sql.replace("?", "%s")


class Connection:
    """A backend-agnostic transactional connection.

    Exposes just what the repository needs, so the rest of the codebase never
    has to know which engine is underneath.
    """

    def __init__(self, raw: Any, dialect: str):
        self._raw = raw
        self.dialect = dialect

    def execute(self, sql: str, params: Sequence[Any] = ()) -> Any:
        return self._raw.execute(_translate(sql, self.dialect, bool(params)), params)

    def insert_returning_id(self, sql: str, params: Sequence[Any] = ()) -> int:
        """Insert one row and return its generated primary key."""
        if self.dialect == "postgres":
            cursor = self.execute(f"{sql.rstrip().rstrip(';')} RETURNING id", params)
            row = cursor.fetchone()
            return int(row["id"])
        return int(self.execute(sql, params).lastrowid)

    def commit(self) -> None:
        self._raw.commit()

    def rollback(self) -> None:
        self._raw.rollback()

    def close(self) -> None:
        self._raw.close()


# Schema creation is idempotent but not free, and on Postgres concurrent DDL can
# block, so each distinct database is prepared once per process.
_prepared: set = set()
_prepare_lock = threading.Lock()


def _connect_sqlite(url: str) -> Any:
    path = sqlite_path(url)
    if str(path) != ":memory:":
        path.parent.mkdir(parents=True, exist_ok=True)
    raw = sqlite3.connect(str(path), timeout=30.0)
    raw.row_factory = sqlite3.Row
    raw.execute("PRAGMA foreign_keys = ON")
    raw.execute("PRAGMA journal_mode = WAL")
    return raw


def _connect_postgres(url: str) -> Any:
    try:
        import psycopg
        from psycopg.rows import dict_row
    except ImportError as exc:  # pragma: no cover - depends on the environment
        raise RuntimeError(
            "PostgreSQL is configured but the driver is missing. "
            "Install it with: pip install 'psycopg[binary]'"
        ) from exc

    try:
        return psycopg.connect(url, row_factory=dict_row, connect_timeout=10)
    except psycopg.OperationalError as exc:
        raise RuntimeError(
            f"Cannot reach PostgreSQL ({describe(url)}): {exc}\n"
            "Start it with: brew services start postgresql@17"
        ) from exc


def connect(target: DbTarget = None) -> Connection:
    """Open a connection, applying the schema the first time this process does."""
    url = resolve_url(target)
    dialect = dialect_of(url)
    raw = _connect_postgres(url) if dialect == "postgres" else _connect_sqlite(url)
    conn = Connection(raw, dialect)

    if url not in _prepared:
        with _prepare_lock:
            if url not in _prepared:
                _apply_schema(conn)
                _prepared.add(url)
    return conn


def _apply_schema(conn: Connection) -> None:
    # Migration must run before the full schema DDL because new indexes
    # reference persona_id which doesn't exist on old tables.
    _migrate_add_persona_id(conn)

    statements = [s.strip() for s in schema_for(conn.dialect).split(";") if s.strip()]
    for statement in statements:
        conn.execute(statement)
    conn.commit()


def _table_exists(conn: Connection, table: str) -> bool:
    """Check whether *table* exists in the database."""
    if conn.dialect == "postgres":
        row = conn.execute(
            "SELECT 1 FROM information_schema.tables WHERE table_name = ?",
            (table,),
        ).fetchone()
    else:
        row = conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name = ?",
            (table,),
        ).fetchone()
    return row is not None


def _has_column(conn: Connection, table: str, column: str) -> bool:
    """Check whether *column* exists on *table*."""
    if not _table_exists(conn, table):
        return True  # Table doesn't exist yet; schema DDL will create it correctly.
    if conn.dialect == "postgres":
        row = conn.execute(
            "SELECT 1 FROM information_schema.columns "
            "WHERE table_name = ? AND column_name = ?",
            (table, column),
        ).fetchone()
    else:
        rows = conn.execute(f"PRAGMA table_info({table})").fetchall()
        row = next((r for r in rows if r["name"] == column), None)
    return row is not None


def _migrate_add_persona_id(conn: Connection) -> None:
    """Add persona_id column to existing tables if they lack it.

    For tables whose primary key changed to include persona_id (position_meta,
    position_snapshots, nav_history, risk_history, news_digests) the table is
    recreated. For auto-id tables (runs, proposals, trades) only the column
    is added.
    """
    if _has_column(conn, "runs", "persona_id"):
        return

    logger.info("Migrating journal: adding persona_id to all tables")

    for table in ("runs", "proposals", "trades"):
        conn.execute(
            f"ALTER TABLE {table} ADD COLUMN persona_id TEXT NOT NULL DEFAULT 'balanced'"
        )

    _recreate_tables = {
        "position_meta": {
            "columns": "persona_id, symbol, entry_date, entry_price, entry_pe, "
                        "peak_price, thesis, target_price, updated_at",
            "select": "'balanced', symbol, entry_date, entry_price, entry_pe, "
                      "peak_price, thesis, target_price, updated_at",
        },
        "position_snapshots": {
            "columns": "persona_id, run_date, symbol, company_name, sector, quantity, "
                       "avg_cost, last_price, market_value, weight_pct, return_pct, "
                       "unrealised_pnl, holding_days, composite_score, beta, "
                       "idiosyncratic_vol, risk_contribution_pct, pct_of_adv, thesis",
            "select": "'balanced', run_date, symbol, company_name, sector, quantity, "
                      "avg_cost, last_price, market_value, weight_pct, return_pct, "
                      "unrealised_pnl, holding_days, composite_score, beta, "
                      "idiosyncratic_vol, risk_contribution_pct, pct_of_adv, thesis",
        },
        "nav_history": {
            "columns": "persona_id, run_date, total_value, invested_value, cash, "
                       "position_count, benchmark_close, daily_return_pct, "
                       "benchmark_return_pct, realised_pnl, unrealised_pnl",
            "select": "'balanced', run_date, total_value, invested_value, cash, "
                      "position_count, benchmark_close, daily_return_pct, "
                      "benchmark_return_pct, realised_pnl, unrealised_pnl",
        },
        "risk_history": {
            "columns": "persona_id, run_date, portfolio_beta, portfolio_vol, "
                       "idio_share_pct, tracking_error_pct, active_share_pct, "
                       "concentration_top5_pct, avg_pairwise_correlation, payload",
            "select": "'balanced', run_date, portfolio_beta, portfolio_vol, "
                      "idio_share_pct, tracking_error_pct, active_share_pct, "
                      "concentration_top5_pct, avg_pairwise_correlation, payload",
        },
        "news_digests": {
            "columns": "persona_id, run_date, macro_summary, market_summary, "
                       "holdings_notes, watchlist_notes, flagged_symbols, "
                       "article_count, high_impact_count, generated_by_llm",
            "select": "'balanced', run_date, macro_summary, market_summary, "
                      "holdings_notes, watchlist_notes, flagged_symbols, "
                      "article_count, high_impact_count, generated_by_llm",
        },
    }

    tokens = _SCHEMA_TOKENS[conn.dialect]

    for table, spec in _recreate_tables.items():
        conn.execute(
            f"ALTER TABLE {table} RENAME TO _{table}_old"
        )

    conn.commit()

    # Re-run schema creation to build the new tables with correct PKs.
    schema_stmts = [
        s.strip()
        for s in schema_for(conn.dialect).split(";")
        if s.strip()
    ]
    for stmt in schema_stmts:
        conn.execute(stmt)
    conn.commit()

    for table, spec in _recreate_tables.items():
        conn.execute(
            f"INSERT INTO {table} ({spec['columns']}) "
            f"SELECT {spec['select']} FROM _{table}_old"
        )
        conn.execute(f"DROP TABLE _{table}_old")

    conn.commit()
    logger.info("Migration complete: persona_id added to all tables")


@contextmanager
def session(target: DbTarget = None) -> Iterator[Connection]:
    """Transactional connection: commits on success, rolls back on error."""
    conn = connect(target)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db(config: Optional[Config] = None) -> str:
    """Ensure the journal exists, returning a description of where it lives."""
    url = resolve_url(config or get_config())
    connect(url).close()
    description = describe(url)
    logger.info("Journal ready: %s", description)
    return description


def reset_prepared_cache() -> None:
    """Forget which databases have been prepared. For tests only."""
    with _prepare_lock:
        _prepared.clear()


def truncate_all(target: DbTarget = None) -> None:
    """Empty every table, keeping the schema. For tests and a clean restart."""
    url = resolve_url(target)
    with session(url) as conn:
        if conn.dialect == "postgres":
            conn.execute(
                "TRUNCATE {} RESTART IDENTITY CASCADE".format(", ".join(TABLES))
            )
        else:
            for table in reversed(TABLES):
                conn.execute(f"DELETE FROM {table}")
            # Restart SQLite's AUTOINCREMENT counters so ids match a fresh
            # database, as TRUNCATE ... RESTART IDENTITY does on Postgres.
            conn.execute(
                "DELETE FROM sqlite_sequence WHERE name IN "
                "('runs','proposals','trades','decision_reviews','learning_lessons')"
            )


def table_counts(target: DbTarget = None) -> Dict[str, int]:
    """Row count per table, for the migration check and status output."""
    counts: Dict[str, int] = {}
    with session(target) as conn:
        for table in TABLES:
            row = conn.execute(f"SELECT COUNT(*) AS n FROM {table}").fetchone()
            counts[table] = int(row["n"])
    return counts
