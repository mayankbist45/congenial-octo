def _migrate_user_book_personas_drop_book_id(conn: Connection) -> None:
    """Personas belong to users only; watchlist provenance lives in frozen_allocation JSON."""
    if not _table_exists(conn, "user_book_personas"):
        return
    if not _has_column(conn, "user_book_personas", "book_id"):
        return
    import json

    logger.info("Migrating user_book_personas: drop book_id column")
    old_rows = [dict(row) for row in conn.execute("SELECT * FROM user_book_personas").fetchall()]
    conn.execute("ALTER TABLE user_book_personas RENAME TO _user_book_personas_old")
    conn.commit()
    for stmt in schema_for(conn.dialect).split(";"):
        cleaned = stmt.strip()
        if cleaned.startswith("CREATE TABLE IF NOT EXISTS user_book_personas"):
            conn.execute(cleaned)
            break
    for row in old_rows:
        meta = json.loads(row.get("frozen_allocation") or "{}")
        book_id = row.get("book_id")
        if book_id and not meta.get("source_book_id"):
            meta["source_book_id"] = book_id
        pending = row.get("pending_overrides") or "{}"
        conn.execute(
            """
            INSERT INTO user_book_personas (
                id, user_id, persona_id, template_persona_id, status,
                frozen_allocation, pending_overrides, provisioned_at, created_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                row["id"],
                row["user_id"],
                row["persona_id"],
                row["template_persona_id"],
                row["status"],
                json.dumps(meta),
                pending,
                row.get("provisioned_at"),
                row["created_at"],
            ),
        )
    conn.execute("DROP TABLE _user_book_personas_old")
    conn.commit()


@contextmanager
def session(target: DbTarget = None) -> Iterator[Connection]:
    """Transactional connection: commits on success, rolls back on error."""
    conn = connect(target)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db(config: Optional[Config] = None) -> str:
    """Ensure the journal exists, returning a description of where it lives."""
    url = resolve_url(config or get_config())
    connect(url).close()
    description = describe(url)
    logger.info("Journal ready: %s", description)
    return description


def reset_prepared_cache() -> None:
    """Forget which databases have been prepared. For tests only."""
    with _prepare_lock:
        _prepared.clear()


def truncate_all(target: DbTarget = None) -> None:
    """Empty every table, keeping the schema. For tests and a clean restart."""
    url = resolve_url(target)
    with session(url) as conn:
        if conn.dialect == "postgres":
            conn.execute(
                "TRUNCATE {} RESTART IDENTITY CASCADE".format(", ".join(TABLES))
            )
        else:
            for table in reversed(TABLES):
                conn.execute(f"DELETE FROM {table}")
            # Restart SQLite's AUTOINCREMENT counters so ids match a fresh
            # database, as TRUNCATE ... RESTART IDENTITY does on Postgres.
            conn.execute(
                "DELETE FROM sqlite_sequence WHERE name IN "
                "('runs','proposals','trades','quarterly_reports',"
                "'quarterly_report_analyses','decision_reviews','learning_lessons',"
                "'meta_decisions')"
            )


def table_counts(target: DbTarget = None) -> Dict[str, int]:
    """Row count per table, for the migration check and status output."""
    counts: Dict[str, int] = {}
    with session(target) as conn:
        for table in TABLES:
            row = conn.execute(f"SELECT COUNT(*) AS n FROM {table}").fetchone()
            counts[table] = int(row["n"])
    return counts
